using WanJieRuLin.Aspects;
using WanJieRuLin.Characters;
using WanJieRuLin.Powers;

namespace WanJieRuLin.Cards;

/// <summary>
/// ★ **事件牌** —— 造成 14 点伤害，抽 1 张牌。
/// ★ 传闻有真有假 —— 打出它抽到的那张牌，就当是「或许是真的」。
/// </summary>
[RegisterCard(typeof(WanJieRuLinCardPool))]
public sealed class HuoXuShiZhenDe : WanJieRuLinCardModel
{
    public HuoXuShiZhenDe() : base(2, CardType.Attack, CardRarity.Event, TargetType.AnyEnemy)
    {
    }

    /// <inheritdoc />
    public override WanJieAspect Aspect => WanJieAspect.Face;

    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new DamageVar(14m, ValueProp.Move)
    ];

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
    {
        ArgumentNullException.ThrowIfNull(cardPlay.Target);
        await DamageCmd.Attack(DynamicVars.Damage.BaseValue)
            .FromCard(this, cardPlay)
            .Targeting(cardPlay.Target)
            .Execute(choiceContext);
        await Draw(choiceContext, 1);
    }

    protected override void OnUpgrade()
    {
    }
}
